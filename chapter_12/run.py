import json
import os
import platform
import time
from pathlib import Path
from typing import Any, Dict, List

from chapter_12_circuit_breakers.run_experiments import (
    AVAILABLE_WORKLOADS,
    run_single_experiment,
)


CHAPTER_NUMBER = 12
EXPERIMENT_ID = "exp-12-continuous-monitoring-circuit-breaker-shutdown"


def _default_evidence_path() -> Path:
    base = os.environ.get("BOOKMAS_EVIDENCE_DIR", "/evidence")
    return Path(base).resolve() / "results.json"


def main() -> None:
    evidence_path = _default_evidence_path()
    evidence_path.parent.mkdir(parents=True, exist_ok=True)

    runs: List[Dict[str, Any]] = []

    # We run all four workloads, both baseline and treatment.
    for workload_id in AVAILABLE_WORKLOADS:
        for variant in ("baseline", "treatment"):
            start = time.time()
            result = run_single_experiment(workload_id=workload_id, mode=variant)
            elapsed = time.time() - start

            # Basic success heuristic: run completed and produced aggregate metrics.
            agg = result["aggregate_metrics"]

            metrics: Dict[str, float] = {}
            metrics["tasks_executed"] = float(agg["tasks_executed"])
            metrics["tasks_scheduled"] = float(agg["tasks_scheduled"])
            metrics["breaker_open_transitions"] = float(agg["breaker_open_transitions"])
            metrics["shutdown_triggered"] = float(1.0 if agg["shutdown_triggered"] else 0.0)
            metrics["total_wall_clock_runtime_ms"] = float(agg["total_wall_clock_runtime_ms"])

            run_record: Dict[str, Any] = {
                "variant": variant,
                "workload_id": workload_id,
                "run_id": f"{workload_id}-{variant}",
                "success": True,
                "metrics": metrics,
                # Extra, non-metric informational fields are allowed:
                "raw_aggregate": agg,
                "config": result["config"],
                "num_events": len(result["per_task_events"]),
                "runtime_measurement_overhead_s": elapsed,
            }
            runs.append(run_record)

    evidence: Dict[str, Any] = {
        "chapter": CHAPTER_NUMBER,
        "experiment_id": EXPERIMENT_ID,
        "environment": {
            "os": platform.platform(),
            "python": platform.python_version(),
        },
        "runs": runs,
        "notes": (
            "Evidence generated by run.py for chapter 12 circuit breaker "
            "experiment. Metrics are derived from actual instrumented execution "
            "of baseline and treatment agents across workloads WL1–WL4."
        ),
    }

    with evidence_path.open("w", encoding="utf-8") as f:
        json.dump(evidence, f, indent=2)


if __name__ == "__main__":  # pragma: no cover
    main()
