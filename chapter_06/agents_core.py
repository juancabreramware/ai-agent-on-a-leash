from __future__ import annotations

"""Core agent stubs used by both baseline and bounded orchestrator.

These agents are deterministic and do **not** call real LLMs or networks.
They simulate behavior patterns needed for the experiment:

- SimpleAgent: converges in a small number of steps (used for WL1, WL3).
- MisbehavingAgentStub: never self-terminates and tends to over-use tools
  (used for WL2, WL4 and as a stress core for WL3).

Each agent exposes a common interface so the orchestrator and baseline loop
can treat them uniformly.
"""

from dataclasses import dataclass
from typing import Any, Dict, Optional, Protocol


class ToolCall(Protocol):
    """Protocol for a tool invocation description returned by agents."""

    name: str
    payload: Dict[str, Any]


@dataclass
class AgentStepResult:
    """Result of a single agent planning step.

    Attributes
    ----------
    content: str
        Text content generated by the agent at this step.
    tool_name: Optional[str]
        Name of the tool to call, if any.
    tool_payload: Optional[Dict[str, Any]]
        Tool arguments, if a tool call is requested.
    stop: bool
        Whether the agent believes it has finished the task.
    estimated_tokens: int
        Simulated token usage for this step.
    """

    content: str
    tool_name: Optional[str]
    tool_payload: Optional[Dict[str, Any]]
    stop: bool
    estimated_tokens: int


class Agent(Protocol):
    """Protocol for agent stubs."""

    def reset(self, task: str) -> None:  # pragma: no cover - trivial
        ...

    def step(self, observation: Optional[str]) -> AgentStepResult:
        ...


class SimpleAgent:
    """A simple, well-behaved agent stub.

    - For WL1 (normal task), it converges in a small fixed number of steps.
    - For WL3 (API-heavy task), it iterates through a requested number of
      services and asks to call a metrics tool for each.

    This behavior is configured via the `mode` and `max_internal_steps`.
    """

    def __init__(self, mode: str = "normal", services_to_process: int = 0) -> None:
        self.mode = mode
        self.services_to_process = services_to_process
        self._task: str = ""
        self._internal_step: int = 0
        self._processed_services: int = 0

    def reset(self, task: str) -> None:
        self._task = task
        self._internal_step = 0
        self._processed_services = 0

    def step(self, observation: Optional[str]) -> AgentStepResult:
        self._internal_step += 1

        # Simulate token usage as a small increasing number.
        estimated_tokens = 50 + 5 * self._internal_step

        if self.mode == "normal":
            # Converge after 3 steps.
            if self._internal_step < 3:
                return AgentStepResult(
                    content=f"Thinking step {self._internal_step} for task: {self._task}",
                    tool_name=None,
                    tool_payload=None,
                    stop=False,
                    estimated_tokens=estimated_tokens,
                )
            else:
                return AgentStepResult(
                    content="Here is the final summary and three next steps.",
                    tool_name=None,
                    tool_payload=None,
                    stop=True,
                    estimated_tokens=estimated_tokens,
                )

        if self.mode == "api_heavy":
            # Request metrics for each service.
            if self._processed_services < self.services_to_process:
                service_id = self._processed_services
                self._processed_services += 1
                return AgentStepResult(
                    content=f"Requesting metrics for service {service_id}",
                    tool_name="fetch_metrics",
                    tool_payload={"service_id": service_id},
                    stop=False,
                    estimated_tokens=estimated_tokens,
                )
            else:
                # Summarize
                return AgentStepResult(
                    content="Computed summary table of metrics.",
                    tool_name=None,
                    tool_payload=None,
                    stop=True,
                    estimated_tokens=estimated_tokens,
                )

        # Default: behave like normal
        return AgentStepResult(
            content=f"Default mode step {self._internal_step}",
            tool_name=None,
            tool_payload=None,
            stop=self._internal_step >= 3,
            estimated_tokens=estimated_tokens,
        )


class MisbehavingAgentStub:
    """Agent stub that never converges on its own.

    It may:
    - Continuously refine its plan without ever setting stop=True.
    - For DoS-like tasks, request the same tool on every step.
    """

    def __init__(self, mode: str = "runaway", tool_name: Optional[str] = None) -> None:
        self.mode = mode
        self.tool_name = tool_name
        self._task: str = ""
        self._step_count: int = 0

    def reset(self, task: str) -> None:
        self._task = task
        self._step_count = 0

    def step(self, observation: Optional[str]) -> AgentStepResult:
        self._step_count += 1
        estimated_tokens = 60 + 2 * self._step_count

        if self.tool_name:
            # Always request the same tool, e.g., for WL4 DoS.
            return AgentStepResult(
                content=f"Step {self._step_count}: calling {self.tool_name} again.",
                tool_name=self.tool_name,
                tool_payload={"counter": self._step_count},
                stop=False,
                estimated_tokens=estimated_tokens,
            )

        # Runaway refinement without tool use.
        return AgentStepResult(
            content=f"Step {self._step_count}: refining the plan endlessly.",
            tool_name=None,
            tool_payload=None,
            stop=False,
            estimated_tokens=estimated_tokens,
        )
