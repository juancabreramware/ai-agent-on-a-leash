import json
import os
import sys
import time
from typing import Any, Dict, List

from src.tools import reset_side_effect_store
from src.workloads import (
    run_workload_baseline,
    run_workload_treatment,
    WORKLOAD_IDS,
)


CHAPTER_NUMBER = 9
EXPERIMENT_ID = "exp-ch09-human-approval-gates-v1"


def _get_env_info() -> Dict[str, str]:
    return {
        "os": os.name,
        "python": sys.version.split()[0],
    }


def main() -> None:
    evidence_dir = os.environ.get("BOOKMAS_EVIDENCE_DIR", "/evidence")
    os.makedirs(evidence_dir, exist_ok=True)
    evidence_path = os.path.join(evidence_dir, "results.json")

    runs: List[Dict[str, Any]] = []

    for workload_id in WORKLOAD_IDS:
        # Baseline run
        reset_side_effect_store()
        baseline_run_id = f"{workload_id}-baseline-{int(time.time() * 1000)}"
        baseline_result = run_workload_baseline(workload_id)
        runs.append(
            {
                "variant": "baseline",
                "workload_id": workload_id,
                "run_id": baseline_run_id,
                "success": bool(baseline_result.get("success", False)),
                # Metrics must all be numbers
                "metrics": {
                    k: float(v)
                    for k, v in baseline_result.get("metrics", {}).items()
                    if isinstance(v, (int, float))
                },
                "details": baseline_result.get("details", {}),
            }
        )

        # Treatment run
        reset_side_effect_store()
        treatment_run_id = f"{workload_id}-treatment-{int(time.time() * 1000)}"
        treatment_result = run_workload_treatment(workload_id)
        runs.append(
            {
                "variant": "treatment",
                "workload_id": workload_id,
                "run_id": treatment_run_id,
                "success": bool(treatment_result.get("success", False)),
                "metrics": {
                    k: float(v)
                    for k, v in treatment_result.get("metrics", {}).items()
                    if isinstance(v, (int, float))
                },
                "details": treatment_result.get("details", {}),
            }
        )

    evidence: Dict[str, Any] = {
        "chapter": CHAPTER_NUMBER,
        "experiment_id": EXPERIMENT_ID,
        "environment": _get_env_info(),
        "runs": runs,
        "notes": "Auto-generated by run.py based on actual instrumented execution.",
    }

    with open(evidence_path, "w", encoding="utf-8") as f:
        json.dump(evidence, f, indent=2, sort_keys=True)


if __name__ == "__main__":
    main()
