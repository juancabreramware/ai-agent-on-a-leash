import json
import os
import sys
import platform
from typing import Dict, Any, List

from chapter_03.workloads import run_all_workloads


EXPERIMENT_ID = "exp-3-least-privilege-capability-authz-v1"
CHAPTER_NUMBER = 3


def get_evidence_dir() -> str:
    env_dir = os.environ.get("BOOKMAS_EVIDENCE_DIR")
    if env_dir:
        base = env_dir
    else:
        base = "/evidence"
    os.makedirs(base, exist_ok=True)
    return base


def main() -> None:
    runs: List[Dict[str, Any]] = []

    # Run all workloads for both variants
    for variant in ("baseline", "treatment"):
        variant_results = run_all_workloads(variant)
        for wr in variant_results:
            run_record: Dict[str, Any] = {
                "variant": variant,
                "workload_id": wr.workload_id,
                "run_id": wr.run_id,
                "success": wr.success,
                "metrics": {
                    # All metrics must be numbers
                    "unauthorized_actions_executed": float(wr.metrics.get("unauthorized_actions_executed", 0)),
                    "unauthorized_actions_blocked": float(wr.metrics.get("unauthorized_actions_blocked", 0)),
                    "authorized_actions_executed": float(wr.metrics.get("authorized_actions_executed", 0)),
                    "capability_escalation_requests_denied": float(wr.metrics.get("capability_escalation_requests_denied", 0)),
                    "capability_escalation_requests_granted": float(wr.metrics.get("capability_escalation_requests_granted", 0)),
                    "secrets_exposed_to_agent": float(wr.metrics.get("secrets_exposed_to_agent", 0)),
                },
            }
            runs.append(run_record)

    evidence: Dict[str, Any] = {
        "chapter": CHAPTER_NUMBER,
        "experiment_id": EXPERIMENT_ID,
        "environment": {
            "os": platform.system(),
            "python": sys.version.split(" ")[0],
        },
        "runs": runs,
        "notes": "Evidence generated by run.py for experiment exp-3-least-privilege-capability-authz-v1. Metrics are derived from deterministic rule-based workloads; no stochastic LLM behavior is involved.",
    }

    evidence_dir = get_evidence_dir()
    out_path = os.path.join(evidence_dir, "results.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(evidence, f, indent=2, sort_keys=True)


if __name__ == "__main__":
    main()
